export const strings = { ar, en };

export function makeT(lang) {
  const table = strings[lang] || ar;
  return (key) => table[key] ?? key;
}

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
export function num(n, lang) {
  const s = String(n);
  return lang === 'ar' ? s.replace(/\d/g, (d) => AR_DIGITS[d]) : s;
}
